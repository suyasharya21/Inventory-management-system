import ExcelJS from 'exceljs';
import { writeFile } from 'node:fs/promises';
import { basename } from 'node:path';
import { businessService, reportService } from './services.mjs';

const currencyKeys = new Set(['sellingPrice', 'costPrice', 'stockValue', 'salesValue', 'listPrice', 'listTotal', 'unitPrice', 'discountAmount', 'total', 'grossProfit', 'oldValue', 'newValue', 'marginBefore', 'marginAfter', 'expectedValue', 'actualValue']);

export async function exportReportExcel(reportType, filters, filePath) {
  const report = reportService.view(reportType, filters);
  const business = businessService.getProfile();
  const workbook = new ExcelJS.Workbook();
  workbook.creator = 'StockSense by Sociverse';
  workbook.created = new Date();
  workbook.properties.title = report.title;
  workbook.properties.subject = `Inventory report for ${business.name}`;

  const summarySheet = workbook.addWorksheet('Summary', { views: [{ showGridLines: false }] });
  summarySheet.columns = [{ width: 28 }, { width: 44 }];
  summarySheet.addRow([`${business.name} - ${report.title}`]);
  summarySheet.mergeCells('A1:B1');
  styleTitle(summarySheet.getCell('A1'));
  summarySheet.addRow(['Owner', business.ownerName]);
  summarySheet.addRow(['Generated', report.generatedAt]);
  summarySheet.addRow(['Generated by', business.currentUser.name]);
  summarySheet.addRow(['Currency', business.currency]);
  summarySheet.addRow([]);
  summarySheet.addRow(['Metric', 'Value']);
  styleHeader(summarySheet.getRow(summarySheet.rowCount));
  for (const [key, value] of Object.entries(report.summary)) {
    const row = summarySheet.addRow([summaryLabel(key), value]);
    if (typeof value === 'number' && /(value|sales|profit|spend|budget|cost|revenue|discount)/i.test(key)) row.getCell(2).numFmt = currencyFormat(business.currency);
  }
  summarySheet.addRow([]);
  summarySheet.addRow(['Developed by Sociverse', 'https://sociverse.tech']);

  const detailSheet = workbook.addWorksheet('Details', { views: [{ state: 'frozen', ySplit: 1 }] });
  detailSheet.columns = report.columns.map((column) => ({ header: column.label, key: column.key, width: Math.max(14, Math.min(38, column.label.length + 8)) }));
  styleHeader(detailSheet.getRow(1));
  for (const item of report.rows) {
    const row = detailSheet.addRow(Object.fromEntries(report.columns.map((column) => [column.key, serializeCell(item[column.key])] )));
    report.columns.forEach((column, index) => {
      if (currencyKeys.has(column.key)) row.getCell(index + 1).numFmt = currencyFormat(business.currency);
      if (/Percent|margin/i.test(column.key)) row.getCell(index + 1).numFmt = '0.00';
    });
  }
  detailSheet.autoFilter = { from: { row: 1, column: 1 }, to: { row: Math.max(1, detailSheet.rowCount), column: Math.max(1, report.columns.length) } };
  detailSheet.eachRow((row, rowNumber) => {
    if (rowNumber > 1 && rowNumber % 2 === 0) row.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFF5F8F8' } };
  });

  const filterSheet = workbook.addWorksheet('Filters Used', { views: [{ showGridLines: false }] });
  filterSheet.columns = [{ width: 28 }, { width: 60 }];
  filterSheet.addRow(['Filter', 'Value']);
  styleHeader(filterSheet.getRow(1));
  const filterEntries = Object.entries(filters ?? {});
  if (!filterEntries.length) filterSheet.addRow(['Filters', 'No additional filters applied']);
  for (const [key, value] of filterEntries) filterSheet.addRow([humanize(key), serializeCell(value)]);
  filterSheet.addRow(['Generated at', report.generatedAt]);

  const buffer = await workbook.xlsx.writeBuffer();
  await writeFile(filePath, Buffer.from(buffer));
  reportService.recordExport(reportType, filters, basename(filePath));
  return { filePath, fileName: basename(filePath), rows: report.rows.length };
}

function styleTitle(cell) {
  cell.font = { name: 'Aptos Display', size: 18, bold: true, color: { argb: 'FFFFFFFF' } };
  cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF233044' } };
  cell.alignment = { vertical: 'middle', horizontal: 'left' };
  cell.border = { bottom: { style: 'medium', color: { argb: 'FF2F6F73' } } };
  cell.worksheet.getRow(cell.row).height = 32;
}

function styleHeader(row) {
  row.font = { bold: true, color: { argb: 'FFFFFFFF' } };
  row.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF233044' } };
  row.alignment = { vertical: 'middle' };
}

function currencyFormat(currency) {
  if (currency === 'INR') return '[$Rs-4009] #,##0.00';
  if (currency === 'USD') return '$#,##0.00';
  if (currency === 'EUR') return 'EUR #,##0.00';
  return `${currency} #,##0.00`;
}

function serializeCell(value) {
  if (value === null || value === undefined) return '';
  if (typeof value === 'object') return JSON.stringify(value);
  return value;
}

function humanize(value) {
  return String(value).replace(/([a-z])([A-Z])/g, '$1 $2').replace(/_/g, ' ').replace(/^./, (letter) => letter.toUpperCase());
}

function summaryLabel(key) {
  return ({ rowCount: 'Matching records', quantity: 'Total quantity', revenue: 'Sales after discounts', discountsGiven: 'Discounts given', purchaseSpend: 'Stock purchase cost', grossProfit: 'Profit after product cost', productCount: 'Products', totalQuantity: 'Total quantity', stockValue: 'Stock value at cost', lowStockCount: 'Low-stock products', agingProductCount: 'Products below sales target', noSaleProductCount: 'Products with no sales', totalCurrentQuantity: 'Current quantity in aging products', slowStockValue: 'Value tied up in aging products' })[key] ?? humanize(key);
}
